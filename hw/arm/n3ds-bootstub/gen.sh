#!/bin/sh
# Regenerate ../n3ds_bootstub.c from boot11.S / boot9.S (needs arm-none-eabi-as/objcopy).
set -e
cd "$(dirname "$0")"
arm-none-eabi-as -march=armv6k boot11.S -o boot11.o && arm-none-eabi-objcopy -O binary boot11.o boot11.bin
arm-none-eabi-as -march=armv5te boot9.S -o boot9.o && arm-none-eabi-objcopy -O binary boot9.o boot9.bin
python3 - <<'PY'
import struct
out = ['/* Generated by hw/arm/n3ds-bootstub/gen.sh from boot11.S and boot9.S - do not edit. */',
       '#include "qemu/osdep.h"', '#include "hw/arm/n3ds_bootstub.h"', '']
for name in ('boot11', 'boot9'):
    d = open(name + '.bin', 'rb').read()
    d += b'\0' * ((-len(d)) % 4)
    w = struct.unpack('<%dI' % (len(d) // 4), d)
    out.append('const uint32_t n3ds_%s_stub[%d] = {' % (name, len(w)))
    for i in range(0, len(w), 6):
        out.append('    ' + ', '.join('0x%08x' % x for x in w[i:i+6]) + ',')
    out.append('};'); out.append('')
open('../n3ds_bootstub.c', 'w').write('\n'.join(out))
PY
rm -f boot11.o boot9.o
ls -la boot11.bin boot9.bin | awk '{print $5, $9}'
